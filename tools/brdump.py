import struct, sys
names = """END IMAGE_PLANE RLE_IMAGE_PLANE OLD_PIXELMAP MATERIAL_OLDEST ADD_MATERIAL OLD_ACTOR OLD_ADD_SIBLING OLD_ADD_CHILD OLD_MATERIAL_INDEX OLD_VERTICES OLD_VERTICES_UV OLD_FACES OLD_MODEL ADD_MODEL ANIM ANIM_TRANSFORM ANIM_RATE FILE_INFO OLD_LIGHT OLD_CAMERA PIVOT MATERIAL_INDEX VERTICES VERTEX_UV OLD_FACES_1 FACE_MATERIAL OLD_MODEL_1 COLOUR_MAP_REF OPACITY_MAP_REF INDEX_BLEND_REF INDEX_SHADE_REF SCREENDOOR_REF PIXELS ADD_MAP ACTOR ACTOR_MODEL ACTOR_TRANSFORM ACTOR_MATERIAL ACTOR_LIGHT ACTOR_CAMERA ACTOR_BOUNDS ACTOR_ADD_CHILD TRANSFORM_MATRIX34 TRANSFORM_MATRIX34_LP TRANSFORM_QUAT TRANSFORM_EULER TRANSFORM_LOOK_UP TRANSFORM_TRANSLATION TRANSFORM_IDENTITY BOUNDS LIGHT_OLD CAMERA FACES OLD_MODEL_2 ACTOR_CLIP_PLANE PLANE SATURN_FACES SATURN_MODEL INDEX_FOG_REF MATERIAL_OLD PIXELMAP MATERIAL LIGHT MODEL VERTEX_COLOUR VERTEX_NORMAL FACE_COLOUR FACE_EQUATION""".split()
d = open(sys.argv[1],'rb').read(); p = 0
from collections import Counter
c = Counter(); seq=[]
while p+8 <= len(d):
    cid, ln = struct.unpack_from('>II', d, p)
    n = names[cid] if cid < len(names) else f"?{cid}"
    c[n]+=1
    if len(seq)<int(sys.argv[2]) if len(sys.argv)>2 else 40: seq.append((p,n,ln,d[p+8:p+8+min(ln,24)].hex()))
    p += 8+ln
for s in seq: print("%06x %-22s %6d %s"%s)
print(dict(c), "end", p, len(d))
